package helloworld;

/**
 *@author みく
 *Enzanshi02クラスは、"Hello "と"World"の二つの文字を繋げて、"Hello World"と出力するプログラムです。
 */
public class Enzanshi02 {
	
	/**
	 * mainメソッド
	 * "Hello"と"World"を連結させて出力します。
	 * @param args コマンドライン引数（このプログラムでは使用しません）
	 */
	public static void main(String[] args) {
		String h = "Hello ";
		String w = "World";
		System.out.println(h + w);
	}
}
